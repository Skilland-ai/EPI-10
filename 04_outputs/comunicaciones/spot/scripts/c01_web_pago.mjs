// Tramo 1: web NutriWell → Stripe Checkout (sandbox, 4242) → confirmación.
import { abrirNavegador, clip, MARTA, estado } from './lib.mjs';
const b = await abrirNavegador();
const c = await clip(b, '01_web_pago'); const { page } = c;
await page.goto('https://epi10-nutriwell-demo.vercel.app', { waitUntil: 'networkidle' });
c.marca('web'); await c.pausa(2000); await c.foto('01_web');
await c.scroll(1400, 60); await c.pausa(1200); await c.scroll(900, 40); await c.pausa(1000);
await c.scroll(-2300, 40); await c.pausa(800);
c.marca('comprar');
await Promise.all([page.waitForURL(/checkout\.stripe\.com/, { timeout: 45000 }), c.clic('button:has-text("Probar compra")')]);
await page.waitForSelector('#cardNumber', { timeout: 45000 }); await c.pausa(1500);
c.marca('stripe'); await c.foto('02_stripe');
await c.escribir('#email', MARTA.email, 30);
await c.escribir('#cardNumber', '4242424242424242', 40);
await c.escribir('#cardExpiry', '1230', 60);
await c.escribir('#cardCvc', '123', 60);
await c.escribir('#billingName', MARTA.nombre, 35);
await c.ir('#billingCountry'); await page.selectOption('#billingCountry', 'ES');
await page.locator('#billingPostalCode').fill(MARTA.cp).catch(() => {});
const pass = page.locator('#enableStripePass'); if (await pass.isChecked().catch(() => false)) await pass.uncheck().catch(() => {});
await c.pausa(1000); await c.foto('03_stripe_relleno');
c.marca('pagar');
await c.clic('button[type=submit]:has-text("Pagar")');
await page.waitForURL((u) => !/checkout\.stripe\.com/.test(u.href), { timeout: 60000 });
await page.waitForLoadState('networkidle').catch(() => {});
c.marca('confirmado'); await c.pausa(3000); await c.foto('04_pago_ok');
console.log('URL final', page.url().replace(/session_id=[^&]+/, 'session_id=…'));
estado('pagado', new Date().toISOString());
await c.cerrar(); await b.close();
